BEGIN;
CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(email) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    company VARCHAR(150) NOT NULL CHECK (length(trim(company)) > 0)
);
CREATE TABLE resource_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
    title VARCHAR(150) NOT NULL CHECK (length(trim(title)) > 0),
    description VARCHAR(2000) NOT NULL DEFAULT '',
    resource_type VARCHAR(30) NOT NULL CHECK (resource_type IN ('VIRTUAL_MACHINE','DATABASE','OBJECT_STORAGE')),
    region VARCHAR(20) NOT NULL CHECK (region IN ('RU_MOSCOW','RU_SPB','RU_KAZAN')),
    cpu INTEGER NOT NULL,
    ram_gb INTEGER NOT NULL,
    storage_gb INTEGER NOT NULL CHECK (storage_gb BETWEEN 10 AND 10000),
    status VARCHAR(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','APPROVED','PROVISIONED','REJECTED','CANCELLED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INTEGER NOT NULL DEFAULT 0,
    CHECK ((resource_type = 'OBJECT_STORAGE' AND cpu = 0 AND ram_gb = 0)
        OR (resource_type IN ('VIRTUAL_MACHINE','DATABASE') AND cpu BETWEEN 1 AND 64 AND ram_gb BETWEEN 1 AND 512 AND ram_gb >= cpu * 2))
);
CREATE INDEX idx_requests_client ON resource_requests(client_id);
CREATE INDEX idx_requests_status ON resource_requests(status);
COMMIT;
